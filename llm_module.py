# ============================================
# 1. RESPONSE CLEANING
# ============================================

def clean_response(text):
    text = text.strip()
    text = re.sub(r'\s+', ' ', text)
    return text


# ============================================
# 2. SIMPLE RULE-BASED RESPONSES
# ============================================

def rule_based_response(query):
    query = query.lower()

    if "who is narendra modi" in query:
        return "Narendra Modi is the Prime Minister of India."

    if "capital of india" in query:
        return "The capital of India is New Delhi."

    if "who is virat kohli" in query:
        return "Virat Kohli is an Indian international cricketer."

    if "what is python" in query:
        return "Python is a high-level programming language."

    return None


