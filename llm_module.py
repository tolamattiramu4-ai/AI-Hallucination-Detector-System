# ============================================
# 6. QUERY CLASSIFIER
# ============================================

def classify_query(query):
    query = query.lower()

    if "program" in query or "python" in query:
        return "programming"

    if "who is" in query or "what is" in query:
        return "factual"

    return "general"


# ============================================
# 7. RESPONSE GENERATOR PIPELINE
# ============================================

def generate_response(query):

    query_type = classify_query(query)

    print("LLM DEBUG TYPE:", query_type)

    # Step 1: Rule-based
    response = rule_based_response(query)
    if response:
        return clean_response(response), "rule-based"

    # Step 2: Programming
    if query_type == "programming":
        response = generate_programming_response(query)
        if response:
            return clean_response(response), "programmed"

    # Step 3: OpenAI API
    response = openai_response(query)
    if response:
        return clean_response(response), "openai"

    # Step 4: Fallback simulated
    response = simulated_llm_response(query)
    return clean_response(response), "simulated"


# ============================================
# 8. CONFIDENCE SCORING
# ============================================

def confidence_score(source):

    if source == "rule-based":
        return 0.9

    if source == "programmed":
        return 0.95

    if source == "openai":
        return 0.85

    return 0.5


# ============================================
# 9. RESPONSE PACKAGER
# ============================================

def get_ai_response(query):

    start_time = time.time()

    response, source = generate_response(query)
    confidence = confidence_score(source)

    end_time = time.time()
    latency = round(end_time - start_time, 3)

    return {
        "query": query,
        "response": response,
        "source": source,
        "confidence": confidence,
        "latency": latency
    }


# ============================================
# 10. RESPONSE FORMATTER
# ============================================

def format_response(result):

    return f"""
Query: {result['query']}

Response:
{result['response']}

Source: {result['source']}
Confidence: {result['confidence']}
Latency: {result['latency']} sec
"""


